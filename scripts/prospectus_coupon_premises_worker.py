"""Actual ordinary/isolated consumers and independent input-preservation checks."""
from copy import deepcopy
import gzip
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import sys

ROOT, OUT, MODE = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
PREP = ROOT/'docs/implementation/prospectus-execution-authority/reviews/coupon-premises-359'
os.environ['CUDA_VISIBLE_DEVICES']='-1'
PACKAGE = OUT/'installed' if MODE=='installed' else ROOT/'src'
sys.path.insert(0,str(PACKAGE))
from legalmath.prospectus.successor import service, fixed_coupon
from legalmath.prospectus.successor.contracts import digest

def read(path):
    raw=Path(path).read_bytes()
    return json.loads(gzip.decompress(raw) if str(path).endswith('.gz') else raw)

def save(path,value):
    path.parent.mkdir(parents=True,exist_ok=True)
    raw=json.dumps(value,sort_keys=True,ensure_ascii=False).encode()
    if str(path).endswith('.gz'):raw=gzip.compress(raw,mtime=0)
    with path.open('xb') as stream:stream.write(raw)

def products(case):
    source=case['products']
    return read(ROOT/source) if isinstance(source,str) else {k:read(ROOT/v) for k,v in source.items()}

def coupons(answer):
    value=answer['questions']['Q5']['value']
    if 'calculations' in value:return value['calculations']
    return [value.get('calculation',value)]

def expected_scenarios(original, baseline):
    request=original['P1']['payload']['request']
    if request.get('financial_scenario') is not None:
        return [deepcopy(request['financial_scenario'])]
    calculation=request['contract_calculation']
    terms=original['P3']['payload']['contract_terms']['terms']
    if 'periods' not in calculation:
        value=deepcopy(calculation['premises'])
        for key,row in terms.items():
            if key in ('issue_principal','maturity_date'):continue
            value[key]=deepcopy(row['value'])
            value.setdefault('evidence',{})[key]={'source':deepcopy(row['source']),'reason':row['reason']}
        return [value]
    # Dates are enumerated independently from the source-reading oracle, not
    # generated by the candidate schedule. Evidence is the original saved input
    # evidence, whose preservation is separately checked in the whole answer.
    ends=['2026-11-25','2027-11-25','2028-11-25','2029-11-25','2030-11-25','2031-11-25']
    starts=['2026-08-25',*ends[:-1]]
    common=calculation['premises']; values=[]
    for i,(left,right,premise,old) in enumerate(zip(starts,ends,calculation['periods'],coupons(baseline))):
        value={k:deepcopy(common[k]) for k in ('issue_id','source_sha256','premise_kind','calendar','holdings','event_scope')}
        value.update(profile='fixed-coupon.v1',accrual_start=left,accrual_end=right,due_date=right,
                     stub='SHORT_FIRST' if i==0 else 'REGULAR',payment_date=premise['payment_date'],
                     events=deepcopy(premise['events']),evidence=deepcopy(old['source_evidence']))
        for k in ('currency','annual_rate','day_count','frequency','eom','adjustment','rounding','references'):
            value[k]=deepcopy(terms[k]['value'])
        values.append(value)
    assert len(values)==6
    return values

def verify_report(answer, ps):
    assert answer['report_sha256']==digest({k:v for k,v in answer.items() if k!='report_sha256'})
    assert answer['consumed_products']=={k:v['sha256'] for k,v in ps.items()}
    assert not answer['may_execute_transaction'] and not answer['independent_legal_acceptance']

def projected(answer, baseline, expected):
    value=deepcopy(answer)
    actual=coupons(value)
    assert len(actual)==len(expected)
    for coupon,scenario in zip(actual,expected):
        assert coupon.pop('calculation_inputs')==scenario,'Exact validated input mismatch'
    assert {k:v for k,v in value['consumed_products'].items() if k!='P5'}=={k:v for k,v in baseline['consumed_products'].items() if k!='P5'}
    value['consumed_products']['P5']=baseline['consumed_products']['P5']
    value['report_sha256']=baseline['report_sha256']
    assert value==baseline,'Previous complete answer changed beyond named addition and derived hashes'

def mutability(scenario,graph):
    original=deepcopy(scenario)
    candidate=deepcopy(scenario)
    result=fixed_coupon.calculate(candidate,graph)
    original_result=deepcopy(result)
    candidate['events'][0]['id']='mutated-after-return'
    candidate['evidence']['currency']['reason']='mutated-after-return'
    candidate['calendar']['holidays'].append('1900-01-01')
    candidate['holdings'][0]['principal']='changed'
    input_isolation=result==original_result
    candidate=deepcopy(original)
    result=fixed_coupon.calculate(candidate,graph)
    result['events'][0]['id']='mutated-output'
    result['source_evidence']['currency']['reason']='mutated-output'
    if 'calculation_inputs' in result:
        result['calculation_inputs']['calendar']['holidays'].append('1900-01-01')
        result['calculation_inputs']['holdings'][0]['principal']='changed'
    return {'input_changes_do_not_mutate_answer':input_isolation,'output_changes_do_not_mutate_input':candidate==original}

def main():
    for name,checksum in read(PREP/'source-bindings.json').items():
        assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==checksum,name
    if MODE=='installed':
        spec=importlib.util.spec_from_file_location('independent_coupon_oracle',ROOT/'scripts/prospectus_fixed_phase_oracle.py')
        oracle=importlib.util.module_from_spec(spec);spec.loader.exec_module(oracle)
    else:
        sys.path.insert(1,str(ROOT))
        from scripts import prospectus_fixed_phase_oracle as oracle
    rows=[]
    for case in read(PREP/'cases.json'):
        name=case['id'];ps=products(case)
        ps['P5']=service.financial_product(ps['P1'],ps['P2'],ps['P3'])
        answer=service.consume(ps,ROOT,mode='frozen')
        verify_report(answer,ps)
        baseline=answer if MODE=='baseline' else read(PREP/(name+'-answer.json.gz'))
        expected=expected_scenarios(ps,baseline)
        graph=ps['P1']['payload']['graph']
        mutation=mutability(expected[0],graph)
        if MODE=='baseline':
            assert all('calculation_inputs' not in c for c in coupons(answer))
            assert mutation=={'input_changes_do_not_mutate_answer':False,'output_changes_do_not_mutate_input':False}
            save(OUT/(name+'-expected.json.gz'),expected)
            historical=read(ROOT/case['historical_answer'])
            delta=[k for k in set(answer)|set(historical) if answer.get(k)!=historical.get(k)]
            question_delta=[k for k in set(answer['questions'])|set(historical['questions']) if answer['questions'].get(k)!=historical['questions'].get(k)]
            row={'id':name,'missing_calculation_inputs':len(expected),'alias_diagnostic':mutation,
                 'historical_changed_top_level_keys':sorted(delta),'historical_changed_questions':sorted(question_delta)}
        else:
            assert expected==read(PREP/(name+'-expected.json.gz'))
            assert all(mutation.values()),'Mutable output aliases remain'
            projected(answer,baseline,expected)
            previous_p5=read(PREP/(name+'-P5.json.gz'))
            projected_p5=deepcopy(ps['P5'])
            q=projected_p5['payload']['question']['value']
            cs=q['calculations'] if 'calculations' in q else [q.get('calculation',q)]
            for c in cs:c.pop('calculation_inputs')
            projected_p5['sha256']=previous_p5['sha256']
            assert projected_p5==previous_p5,'P5 changed beyond exact input addition'
            row={'id':name,'retained_exact_scenarios':len(expected),'complete_prior_answer_projection_equal':True,'alias_isolation':mutation}
            if name.startswith('danske-'):
                row['independent_source_integer_check']=oracle.check_value(answer['questions']['Q5']['value'],holiday=name.endswith('holiday'),excluded=name.endswith('excluded'))
            # Refusal behavior is tested against actual source/graph data without
            # pretending that these changed hypotheses are actual instrument facts.
            for defect in ('calendar','rounding','event-order'):
                invalid=deepcopy(expected[0])
                if defect=='calendar':invalid['calendar']['valid_until']=invalid['accrual_start']
                elif defect=='rounding':invalid['rounding']['quantum']='0'
                else:
                    payment=next(e for e in invalid['events'] if e['kind']=='payment')
                    payment['at']=invalid['accrual_start']+'T00:00:00Z'
                try:fixed_coupon.calculate(invalid,graph)
                except ValueError:pass
                else:raise AssertionError('Invalid scenario accepted: '+defect)
            # Output-corruption controls rehash the report, so a digest check alone
            # cannot make the exact complete-answer criterion appear effective.
            for defect in ('lost-calendar','changed-fraction','false-settlement'):
                bad=deepcopy(answer); c=coupons(bad)[0]
                if defect=='lost-calendar':c['calculation_inputs'].pop('calendar')
                elif defect=='changed-fraction':c['day_fraction']='0'
                else:c['full_settlement_supported']=True
                bad['report_sha256']=digest({k:v for k,v in bad.items() if k!='report_sha256'})
                try:projected(bad,baseline,expected)
                except (AssertionError,KeyError):pass
                else:raise AssertionError('Corrupted answer accepted: '+defect)
            if MODE=='installed':
                assert answer==read(OUT/'ordinary'/(name+'-answer.json.gz'))
                assert ps['P5']==read(OUT/'ordinary'/(name+'-P5.json.gz'))
        dest=OUT if MODE=='baseline' else OUT/MODE
        save(dest/(name+'-answer.json.gz'),answer);save(dest/(name+'-P5.json.gz'),ps['P5'])
        rows.append(row)
    imports={n:m.__file__ for n,m in sys.modules.items() if (n=='legalmath' or n.startswith('legalmath.')) and getattr(m,'__file__',None)}
    assert imports and all(Path(p).resolve().is_relative_to(PACKAGE.resolve()) for p in imports.values())
    summary={'status':'PASS','mode':MODE,'cases':rows,'full_consumer_cases':len(rows),'coupon_scenarios':22,
             'import_count':len(imports),'whole_task_complete':False,'fresh_extraction':False,
             'complete_ordinary_installed_equality':MODE=='installed'}
    save(OUT/(MODE+'-imports.json'),imports);save(OUT/(MODE+'-summary.json'),summary)
    print(json.dumps({'status':'PASS','mode':MODE,'cases':len(rows),'imports':len(imports)}))

main()
